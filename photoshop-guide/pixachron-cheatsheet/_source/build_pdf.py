#!/usr/bin/env python3
"""Pixachron cheat sheet as a PDF, images embedded losslessly at 1 pt per pixel.
Usage: build_pdf.py <raw dir> <width> <height> <site dir> <out.pdf>
Reads manifest.json / outline.json from the raw dir and the PNGs from <site dir>/img."""
import json, os, sys, zlib, textwrap
from PIL import Image

raw_dir, W, H, site, out = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), sys.argv[4], sys.argv[5]
manifest = json.load(open(os.path.join(raw_dir, "manifest.json")))
outline = json.load(open(os.path.join(raw_dir, "outline.json")))
img_dir = os.path.join(site, "img")

PAGE_W = 1080; MARGIN = 40
REPL = {"−": "-", "→": "->", "⏱": "", "…": "...", "’": "'", "“": '"', "”": '"', "–": "-", "—": "-"}
def clean(s):
    for a, b in REPL.items(): s = s.replace(a, b)
    return s.encode("cp1252", "replace").decode("cp1252")
def pdfstr(s):
    b = clean(s).encode("cp1252", "replace")
    return b"(" + b.replace(b"\\", b"\\\\").replace(b"(", b"\\(").replace(b")", b"\\)") + b")"

objects = []  # list of bytes; object number = index + 1
def add(obj): objects.append(obj); return len(objects)

font_reg = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>")
font_bold = add(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>")
pages = []

def image_obj(png_path):
    im = Image.open(png_path).convert("RGB")
    w, h = im.size
    data = zlib.compress(im.tobytes(), 6)
    return add(b"<< /Type /XObject /Subtype /Image /Width %d /Height %d /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /FlateDecode /Length %d >>\nstream\n" % (w, h, len(data)) + data + b"\nendstream"), w, h

def page(title_lines, img_id, iw, ih, foot):
    # text block height first, so the page height fits
    lines = []
    for font, size, text, col, width in title_lines:
        for ln in (textwrap.wrap(clean(text), width) or [""]): lines.append((font, size, ln, col))
    text_h = sum(s * 1.35 for _, s, _, _ in lines) + 20
    page_h = MARGIN + text_h + ih + MARGIN + 24
    ops = []
    y = page_h - MARGIN
    for font, size, text, col in lines:
        y -= size * 1.35
        ops.append(b"BT /%s %d Tf %s rg 1 0 0 1 %d %d Tm %s Tj ET" % (font.encode(), size, col.encode(), MARGIN, int(y), pdfstr(text)))
    img_y = MARGIN + 24
    ops.append(b"q %d 0 0 %d %d %d cm /Im Do Q" % (iw, ih, MARGIN, img_y))
    ops.append(b"BT /F1 8 Tf 0.55 0.53 0.5 rg 1 0 0 1 %d %d Tm %s Tj ET" % (MARGIN, MARGIN, pdfstr(foot)))
    content = b"\n".join(ops)
    c_id = add(b"<< /Length %d >>\nstream\n" % len(content) + content + b"\nendstream")
    p_id = add(b"PLACEHOLDER")
    pages.append((p_id, c_id, img_id, page_h))
    return p_id

# cover
cover_lines = [("F2", 44, "Pixachron cheat sheet", "0.08 0.08 0.08", 60), ("F1", 13, "Every control, one at a time, at 1 pt per pixel. Each section starts from a reference image; every image after it changes exactly one thing from that reference, named in its heading. View at 100% to see the pixels as rendered.", "0.36 0.35 0.33", 95)]
secs = []
for m in manifest:
    if not secs or secs[-1][0] != m["section"]: secs.append([m["section"], 0])
    secs[-1][1] += 1
secs.append(["Outline mode", len(outline)])
cover_lines.append(("F1", 11, " ", "0 0 0", 95))
for name, cnt in secs: cover_lines.append(("F1", 11, "%s   %d" % (name, cnt), "0.36 0.35 0.33", 95))
cover_lines.append(("F1", 11, " ", "0 0 0", 95))
cover_lines.append(("F1", 9, "Rendered with the Pixachron engine from the installed plugin folder; outline-mode pages drawn from the paths the engine writes. Generated by build_pdf.py in pixachron-cheatsheet/_source.", "0.55 0.53 0.5", 120))
cov_img, cw, ch = image_obj(os.path.join(img_dir, manifest[0]["file"].replace(".rgb", ".png")))
page(cover_lines, cov_img, cw, ch, "Pixachron cheat sheet")

k = 0; total = len(manifest) + len(outline)
for m in manifest:
    k += 1
    img, iw, ih = image_obj(os.path.join(img_dir, m["file"].replace(".rgb", ".png")))
    lines = [("F1", 10, "%s   .   %02d / %d" % (m["section"].lower(), k, total), "1 0.31 0", 100),
             ("F2", 20, m["title"], "0.08 0.08 0.08", 80),
             ("F1", 11, m["note"], "0.36 0.35 0.33", 125)]
    for s in m["settings"]: lines.append(("F1", 9, s, "0.55 0.53 0.5", 150))
    page(lines, img, iw, ih, "Pixachron cheat sheet   .   " + m["section"])
for o in outline:
    k += 1
    img, iw, ih = image_obj(os.path.join(img_dir, o["png"] if "png" in o else "outline_%02d.png" % (outline.index(o) + 1)))
    lines = [("F1", 10, "outline mode   .   %02d / %d" % (k, total), "1 0.31 0", 100),
             ("F2", 20, o["title"], "0.08 0.08 0.08", 80),
             ("F1", 11, o["note"], "0.36 0.35 0.33", 125),
             ("F1", 9, "Domain: " + o["domain"], "0.55 0.53 0.5", 150)]
    page(lines, img, iw, ih, "Pixachron cheat sheet   .   outline mode")

pages_id = len(objects) + 1
kids = b" ".join(b"%d 0 R" % p for p, _, _, _ in pages)
objects.append(b"<< /Type /Pages /Kids [%s] /Count %d >>" % (kids, len(pages)))
for p_id, c_id, img_id, page_h in pages:
    objects[p_id - 1] = b"<< /Type /Page /Parent %d 0 R /MediaBox [0 0 %d %d] /Resources << /Font << /F1 %d 0 R /F2 %d 0 R >> /XObject << /Im %d 0 R >> >> /Contents %d 0 R >>" % (pages_id, PAGE_W, int(page_h), font_reg, font_bold, img_id, c_id)
catalog = add(b"<< /Type /Catalog /Pages %d 0 R >>" % pages_id)

with open(out, "wb") as f:
    f.write(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for i, obj in enumerate(objects, 1):
        offsets.append(f.tell()); f.write(b"%d 0 obj\n" % i + obj + b"\nendobj\n")
    xref = f.tell()
    f.write(b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1))
    for o in offsets: f.write(b"%010d 00000 n \n" % o)
    f.write(b"trailer\n<< /Size %d /Root %d 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objects) + 1, catalog, xref))
print("wrote", out, len(pages), "pages", round(os.path.getsize(out) / 1e6, 1), "MB")
